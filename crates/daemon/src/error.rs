//! Ошибки демона BottleForApps.
//!
//! Строки ошибок попадают пользователю (GUI/CLI → IPC), поэтому они
//! на русском языке — как в `agent::error`.

use std::io;
use std::time::Duration;

use bottle_core::profile::ProfileError;

/// Ошибка операции хранилища профилей.
#[derive(Debug, thiserror::Error)]
pub enum DaemonError {
    /// Ошибка ввода-вывода (чтение/запись файлов хранилища).
    #[error("ошибка ввода-вывода: {0}")]
    Io(#[from] io::Error),
    /// Профиль не прошёл разбор или валидацию (`bottle_core::profile`).
    #[error("некорректный профиль: {0}")]
    Profile(#[from] ProfileError),
    /// Файл `bottles/<id>.toml` не найден.
    #[error("профиль не найден: {id}")]
    NotFound {
        /// Идентификатор запрошенной бутылки.
        id: String,
    },
    /// Бутылки нет в реестре демона, и реестр пуст: GUI ещё не прислал
    /// SyncProfiles (0.3 — профили живут только в памяти демона).
    #[error("бутылка не найдена: {id} (реестр демона пуст — демон ждёт SyncProfiles от GUI)")]
    NotInRegistryEmpty {
        /// Идентификатор запрошенной бутылки.
        id: String,
    },
    /// Локальная копия токена аплаенса отсутствует, хотя дистрибуция
    /// импортирован (или агент отверг токен): восстановить токен нельзя.
    #[error("токен утерян — удалите дистрибуцию bottleforapps (wsl --unregister) и повторите")]
    ApplianceTokenLost,
    /// Версия протокола агента аплаенса несовместима с демоном
    /// (несовпадение в `Hello`/`HelloAck` или ответ `VERSION`).
    #[error("Апплайенс несовместим — выполните обновление (bottle upgrade)")]
    ApplianceIncompatible,
    /// Агент аплаенса не установил соединение или не ответил за
    /// отведённое время.
    #[error("агент аплаенса не ответил за {timeout:?}: тайм-аут")]
    ApplianceTimeout {
        /// Сколько ждали (соединение или ответ на запрос).
        timeout: Duration,
    },
    /// Прочие сбои импорта аплаенса и обмена с агентом; текст уже
    /// сформулирован для пользователя (CLI → IPC).
    #[error("{0}")]
    Appliance(String),
    /// Ошибка службы маршрутов `bottle-svc`: текст — русское сообщение
    /// службы (VALIDATION/IO/INTERNAL), уже готовое для пользователя.
    #[error("{0}")]
    Svc(String),
    /// Ошибка host-сети демона (резолв endpoint'ов, поиск физического
    /// шлюза); текст уже сформулирован для пользователя (CLI → IPC).
    #[error("{0}")]
    HostNet(String),
}
