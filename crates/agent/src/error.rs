//! Ошибки агента BottleForApps.
//!
//! Строки [`AgentError`] попадают пользователю в ответе
//! `AgentReply::Error { message }` (задача 11), поэтому они на русском языке.

use std::io;

/// Ошибка выполнения операции агентом.
#[derive(Debug, thiserror::Error)]
pub enum AgentError {
    /// Идентификатор бутылки не прошёл проверку `bottle_core::profile::validate_id`.
    #[error("недопустимый идентификатор бутылки: допускаются только строчные латинские буквы, цифры и дефис, первый символ — буква или цифра")]
    InvalidId,
    /// Все сетевые слоты 1..=250 заняты.
    #[error("нет свободных сетевых слотов: все 250 заняты")]
    NoFreeSlots,
    /// Внешняя системная команда (например, `ip`) завершилась с ошибкой.
    #[error("команда не удалась: {command}: {stderr}")]
    CommandFailed {
        /// Выполненная команда с аргументами.
        command: String,
        /// Вывод stderr команды (для диагностики).
        stderr: String,
    },
    /// Некорректный конфиг туннеля (например, `.conf` WireGuard):
    /// отсутствуют обязательные ключи или строка не разбирается.
    #[error("некорректный конфиг туннеля: {0}")]
    InvalidConfig(String),
    /// Не удалось поднять туннель (резолв endpoint, handshake и т.п.);
    /// задача 11 маппирует в `bottle_core::protocol::err::TUNNEL_FAILED`.
    #[error("не удалось поднять туннель: {0}")]
    TunnelFailed(String),
    /// Параллельный `up` того же id выиграл гонку провижининга:
    /// бутылка-победитель уже в реестре, проигравший разобрал своё
    /// (TOCTOU-барьер реестра, рулинг M3-бэклога).
    #[error("бутылка {id} поднята параллельной операцией; повторите запрос")]
    BadInstance { id: String },
    /// Ошибка ввода-вывода.
    #[error("ошибка ввода-вывода: {0}")]
    Io(#[from] io::Error),
}
